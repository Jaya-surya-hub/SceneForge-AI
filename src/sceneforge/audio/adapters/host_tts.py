"""Host-assisted TTS adapter.

When running inside Docker, edge-tts may be blocked by Docker NAT.
This adapter checks for pre-generated audio files produced by the host
machine (which has direct network access) and returns them.

Usage:
  1. On the host: python scripts/pre_generate_tts.py --text "..." --output /path/to/audio.mp3
  2. Set TTS_ADAPTER=host_tts and TTS_PRE_GENERATED_PATH=/app/storage/tts/audio.mp3

The adapter verifies the file exists, has non-zero size, and contains
audio data. It does NOT fabricate audio — if the file is missing or
invalid, it raises TTSProviderError.

The manifest records `tts_adapter: host_tts` and `tts_is_mock: false`
so the provenance is honest.
"""

from __future__ import annotations

import os
from typing import Optional

from sceneforge.audio.interfaces import TTSAdapter
from sceneforge.observability.logging import get_logger
from sceneforge.schemas.exceptions import TTSProviderError

log = get_logger(__name__)

_PRE_GENERATED_PATH = os.getenv("TTS_PRE_GENERATED_PATH", "")


class HostTTSAdapter(TTSAdapter):
    """TTS adapter that reads pre-generated audio from the host.

    The audio must be generated BEFORE the job is submitted, using:
      python scripts/pre_generate_tts.py --text "..." --output /path/audio.mp3

    This adapter is NOT a mock — it returns real audio generated by
    edge-tts on the host machine. The provenance is recorded in the manifest.
    """

    adapter_name: str = "host_tts"
    is_mock: bool = False

    def __init__(self, audio_path: Optional[str] = None) -> None:
        self._audio_path = audio_path or _PRE_GENERATED_PATH

    def synthesise(self, text: str, *, voice: Optional[str] = None) -> bytes:
        """Return pre-generated audio bytes from the host.

        Args:
            text:  The narration text (must match what was pre-generated).
            voice: Ignored (voice is set during pre-generation).

        Returns:
            Real audio bytes (MP3 format) from the pre-generated file.

        Raises:
            TTSProviderError: If the pre-generated file is missing, empty,
                             or cannot be read.
        """
        if not self._audio_path:
            raise TTSProviderError(
                "HostTTSAdapter: TTS_PRE_GENERATED_PATH is not set. "
                "Run: python scripts/pre_generate_tts.py --text '...' --output /path/audio.mp3 "
                "and set TTS_PRE_GENERATED_PATH to the output path."
            )

        if not os.path.isfile(self._audio_path):
            raise TTSProviderError(
                f"HostTTSAdapter: pre-generated audio not found at '{self._audio_path}'. "
                "Run pre_generate_tts.py on the host first."
            )

        try:
            with open(self._audio_path, "rb") as f:
                audio_bytes = f.read()
        except OSError as exc:
            raise TTSProviderError(f"HostTTSAdapter: cannot read file: {exc}") from exc

        if len(audio_bytes) == 0:
            raise TTSProviderError("HostTTSAdapter: pre-generated file is empty.")

        log.info(
            "host_tts_loaded",
            path=self._audio_path,
            size=len(audio_bytes),
            text_length=len(text),
        )
        return audio_bytes

    def estimated_duration(self, text: str) -> float:
        """Estimate duration from word count (2.5 words/s)."""
        words = len(text.split())
        return max(1.0, words / 2.5)
